#!/usr/bin/env python3
"""Turn the root certificates in tools/roots/ into src/roots.c, the ones the route look-ups trust.

    python tools/make_roots.py

Cloudflare serves workers.dev with certificates from Google Trust Services (seen 2026-10-30: WE1
under GTS Root R4) or Let's Encrypt, so those roots are kept here, downloaded from pki.goog and
letsencrypt.org. Check a new one's fingerprint against its publisher's before adding it.
"""
import hashlib
import ssl
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CERTS = ROOT / "tools" / "roots"


def main():
    out = [
        "// Generated by tools/make_roots.py from tools/roots/: don't edit. The root certificates the",
        "// route look-ups trust, as one PEM string. SHA-256 fingerprints:",
    ]
    body = []
    for path in sorted(CERTS.glob("*.pem")):
        pem = path.read_text(encoding="ascii").strip()
        der = ssl.PEM_cert_to_DER_cert(pem + "\n")
        fp = hashlib.sha256(der).hexdigest().upper()
        fp = ":".join(fp[i:i + 2] for i in range(0, len(fp), 2))
        out.append(f"//   {path.stem}: {fp}")
        body.append(f"    // {path.stem}")
        body += [f'    "{line}\\n"' for line in pem.splitlines()]
    out += ['#include "roots.h"', "", "const char roots_pem[] ="] + body + ["    ;", ""]
    out.append("const unsigned roots_pem_len = sizeof roots_pem;   // with its terminating NUL, as mbedTLS wants")
    (ROOT / "src" / "roots.c").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(body) and len(list(CERTS.glob('*.pem')))} roots")


if __name__ == "__main__":
    main()
