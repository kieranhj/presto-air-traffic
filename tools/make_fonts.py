#!/usr/bin/env python3
"""Rasterise the fonts the firmware draws text with into src/font_data.c (committed, so a build
doesn't need Pillow). Run again after changing a size here:

    python tools/make_fonts.py

Each font is printable ASCII (32-126) plus character 127 drawn as a copyright sign,
anti-aliased, 4 bits of coverage a pixel, two pixels a byte. Glyphs are rasterised from IBM Plex
Sans Condensed (tools/fonts, SIL Open Font License 1.1, tools/fonts/OFL.txt).
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = [
    # (C name, file, pixel size)
    ("font_small", "IBMPlexSansCondensed-Medium.ttf", 15),
    ("font_large", "IBMPlexSansCondensed-SemiBold.ttf", 22),
]
FIRST, LAST = 32, 127      # 127 is drawn as the copyright sign, for map credits


def rasterise(path: Path, size: int):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = "©" if code == 127 else chr(code)
        advance = round(font.getlength(ch))
        box = font.getbbox(ch, anchor="ls")     # relative to the pen on the baseline
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
            px = img.tobytes()
            for y in range(h):
                row = [px[y * w + x] >> 4 for x in range(w)]
                if w & 1:
                    row.append(0)
                for x in range(0, len(row), 2):
                    data.append((row[x] << 4) | row[x + 1])
        glyphs.append((offset, w, h, box[0], box[1], advance))
    return ascent, descent, glyphs, data


def main():
    out = [
        "// Generated by tools/make_fonts.py: don't edit. Rasterised from IBM Plex Sans Condensed",
        "// (tools/fonts, SIL Open Font License 1.1).",
        '#include "font.h"',
        "",
    ]
    for name, file, size in FONTS:
        ascent, descent, glyphs, data = rasterise(ROOT / "tools" / "fonts" / file, size)
        out.append(f"static const uint8_t {name}_bits[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const font_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for (offset, w, h, x, y, adv), code in zip(glyphs, range(FIRST, LAST + 1)):
            c = "©" if code == 127 else chr(code)
            shown = c if c not in "\\'" else "\\" + c
            out.append(f"    {{{offset}, {w}, {h}, {x}, {y}, {adv}}},  // '{shown}'")
        out.append("};")
        out.append(f"const font_t {name} = {{{name}_bits, {name}_glyphs, {FIRST}, {LAST}, "
                   f"{ascent}, {descent}, {ascent + descent}}};")
        out.append("")
        print(f"{name}: {size} px, {len(data)} bytes, line {ascent + descent} px")
    (ROOT / "src" / "font_data.c").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
